xt::xarray<float> to_2d(const nlohmann::json &arr)
{
  const size_t n_y = arr.size();
  const size_t n_x = arr.at(0).size();
  xt::xarray<float> out;
  out.resize({n_y, n_x});
  for (size_t i_y = 0; i_y < n_y; ++i_y)
  {
    for (size_t i_x = 0; i_x < n_x; ++i_x)
    {
      out(i_y, i_x) = arr.at(i_y).at(i_x).get<float>();
    }
  }
  return out;
}

xt::xarray<bool> to_2d_bool_from_3d(const nlohmann::json &arr, size_t i_c)
{
  const auto &plane = arr.at(i_c);
  const size_t n_y = plane.size();
  const size_t n_x = plane.at(0).size();
  xt::xarray<bool> out;
  out.resize({n_y, n_x});
  for (size_t i_y = 0; i_y < n_y; ++i_y)
  {
    for (size_t i_x = 0; i_x < n_x; ++i_x)
    {
      out(i_y, i_x) = plane.at(i_y).at(i_x).get<bool>();
    }
  }
  return out;
}

xt::xarray<float> to_3d(const nlohmann::json &arr)
{
  const size_t n_c = arr.size();
  const size_t n_y = arr.at(0).size();
  const size_t n_x = arr.at(0).at(0).size();
  xt::xarray<float> out;
  out.resize({n_c, n_y, n_x});
  for (size_t i_c = 0; i_c < n_c; ++i_c)
  {
    for (size_t i_y = 0; i_y < n_y; ++i_y)
    {
      for (size_t i_x = 0; i_x < n_x; ++i_x)
      {
        out(i_c, i_y, i_x) = arr.at(i_c).at(i_y).at(i_x).get<float>();
      }
    }
  }
  return out;
}
