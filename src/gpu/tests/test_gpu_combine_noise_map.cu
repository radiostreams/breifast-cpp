TEST_CASE("gpu_combine_noise_map_rms matches a seeded-random 23-pixel map against a numpy reference",
          "[gpu][combine_noise_map]")
{
  // numpy in float64: sqrt(maximum(rms, rms_floor)^2 + 4 * selfnoise_offset + 1 * dde_noise).
  const std::vector<float> expected = {
      0.581607496F, 0.533840379F, 0.671029735F, 0.704374426F, 0.532710688F, 0.540847108F, 0.567976893F, 0.596187768F,
      0.537628664F, 0.544653828F, 0.703467827F, 0.695912945F, 0.570838017F, 0.741753753F, 0.647694462F, 0.550506564F,
      0.598721968F, 0.552118774F, 0.701788966F, 0.553053215F, 0.528811385F, 0.526588069F, 0.761708357F,
  };

