// Runs gpu_combine_noise_map with an RMS map. `out_noise_map` starts filled with `prefill` on the device, like
// per-thread scratch that still holds the previous band.
std::vector<float> run_gpu_combine_noise_map_rms(const std::vector<float> &rms_values, float floor,
                                                 const std::vector<float> &selfnoise_values,
                                                 const std::vector<float> &dde_values, float prefill = 0.F)
{
  const size_t n_plane_pixels = rms_values.size();

  const auto device_rms = upload(rms_values);
  const auto device_floor = upload(std::vector<float>{floor});
  const auto device_selfnoise = upload(selfnoise_values);
  const auto device_dde = upload(dde_values);
  auto device_out = upload(std::vector<float>(n_plane_pixels, prefill));

  const Stream stream;
  gpu_combine_noise_map(device_rms, device_floor, device_selfnoise, device_dde, selfnoise_scale, dde_scale, device_out,
                        n_plane_pixels, stream.get());
  return download(device_out, stream);
}

// Runs gpu_combine_noise_map without an RMS map, so with the constant base noise.
std::vector<float> run_gpu_combine_noise_map_constant(const std::vector<float> &selfnoise_values,
                                                      const std::vector<float> &dde_values, float prefill = 0.F)
{
  const size_t n_plane_pixels = selfnoise_values.size();

  const auto device_base_noise = upload(std::vector<float>{base_noise});
  const auto device_selfnoise = upload(selfnoise_values);
  const auto device_dde = upload(dde_values);
  auto device_out = upload(std::vector<float>(n_plane_pixels, prefill));

  const Stream stream;
  gpu_combine_noise_map(nullptr, device_base_noise, device_selfnoise, device_dde, selfnoise_scale, dde_scale,
                        device_out, n_plane_pixels, stream.get());
  return download(device_out, stream);
}

// A deterministic ramp for the coverage cases, where a hand-written expected array would be unwieldy.
std::vector<float> make_pattern(size_t n_plane_pixels, float scale, int stride, int modulus)
{
  std::vector<float> values(n_plane_pixels);
  for (size_t i_pixel = 0; i_pixel < n_plane_pixels; ++i_pixel)
  {
    values[i_pixel] = scale * static_cast<float>(static_cast<int>((i_pixel * stride) % modulus));
  }
  return values;
}

// References computed on the host with the documented formula, independent of the kernels.
std::vector<float> host_combine_noise_map_rms(const std::vector<float> &rms_values, float floor,
                                              const std::vector<float> &selfnoise_values,
                                              const std::vector<float> &dde_values)
{
  std::vector<float> out(rms_values.size());
  for (size_t i_pixel = 0; i_pixel < rms_values.size(); ++i_pixel)
  {
    const float base = std::max(rms_values[i_pixel], floor);
    out[i_pixel] = std::sqrt(base * base + selfnoise_scale * selfnoise_values[i_pixel] +
                             dde_scale * dde_values[i_pixel]);
  }
  return out;
}

std::vector<float> host_combine_noise_map_constant(const std::vector<float> &selfnoise_values,
                                                   const std::vector<float> &dde_values)
{
  std::vector<float> out(selfnoise_values.size());
  for (size_t i_pixel = 0; i_pixel < selfnoise_values.size(); ++i_pixel)
  {
    out[i_pixel] =
        std::sqrt(base_noise * base_noise + selfnoise_scale * selfnoise_values[i_pixel] + dde_scale * dde_values[i_pixel]);
  }
  return out;
}

void check_noise_maps_match_host(size_t n_plane_pixels)
{
  const std::vector<float> rms_values = make_pattern(n_plane_pixels, 0.01F, 7, 100);
  const std::vector<float> selfnoise_values = make_pattern(n_plane_pixels, 0.001F, 13, 50);
  const std::vector<float> dde_values = make_pattern(n_plane_pixels, 0.001F, 29, 40);
  constexpr float floor = 0.5F;

  const auto expected_rms = host_combine_noise_map_rms(rms_values, floor, selfnoise_values, dde_values);
  const auto out_rms = run_gpu_combine_noise_map_rms(rms_values, floor, selfnoise_values, dde_values);
  REQUIRE(out_rms.size() == n_plane_pixels);
  CHECK_THAT(out_rms, Catch::Matchers::Approx(expected_rms).epsilon(1e-5).margin(1e-5));

  const auto expected_constant = host_combine_noise_map_constant(selfnoise_values, dde_values);
  const auto out_constant = run_gpu_combine_noise_map_constant(selfnoise_values, dde_values);
  REQUIRE(out_constant.size() == n_plane_pixels);
  CHECK_THAT(out_constant, Catch::Matchers::Approx(expected_constant).epsilon(1e-5).margin(1e-5));
}
