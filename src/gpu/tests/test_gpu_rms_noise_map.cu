TEST_CASE("gpu_rms_noise_map matches a seeded-random 5x9 plane with an even box against a numpy reference",
          "[gpu][rms_noise_map]")
{
  const auto out_rms = run_gpu_rms_noise_map(plane, n_y, n_x, boxsize);

  REQUIRE(out_rms.size() == n_pixels);
  CHECK_THAT(out_rms, Catch::Matchers::Approx(rms_reference).epsilon(1e-5));
}

TEST_CASE("gpu_rms_noise_map overwrites stale scratch and output buffers", "[gpu][rms_noise_map]")
{
  const auto out_rms = run_gpu_rms_noise_map(plane, n_y, n_x, boxsize, -12345.F);

  REQUIRE(out_rms.size() == n_pixels);
  CHECK_THAT(out_rms, Catch::Matchers::Approx(rms_reference).epsilon(1e-5));
}

TEST_CASE("gpu_rms_noise_map rejects a zero dimension", "[gpu][rms_noise_map]")
{
  DeviceVector<float> device_plane(1);
  DeviceVector<float> device_rows(1);
  DeviceVector<float> device_out(1);

  cudaStream_t stream{};
  gpuStreamCreate(&stream);

  REQUIRE_THROWS_AS(gpu_rms_noise_map(thrust::raw_pointer_cast(device_plane.data()), 0, n_x, boxsize,
                                      thrust::raw_pointer_cast(device_rows.data()),
                                      thrust::raw_pointer_cast(device_out.data()), stream),
                    std::runtime_error);
  REQUIRE_THROWS_AS(gpu_rms_noise_map(thrust::raw_pointer_cast(device_plane.data()), n_y, 0, boxsize,
                                      thrust::raw_pointer_cast(device_rows.data()),
                                      thrust::raw_pointer_cast(device_out.data()), stream),
                    std::runtime_error);

  gpuStreamDestroy(stream);
}

TEST_CASE("gpu_rms_noise_map covers blocks in both dimensions on a large plane", "[gpu][rms_noise_map]")
{
  constexpr size_t rows = 300;
  constexpr size_t cols = 257;
  constexpr long box = 4;

  const std::vector<float> big_plane = make_plane(rows * cols, 12345ULL);
  const std::vector<float> expected = host_rms_noise_map(big_plane, rows, cols, box);
  const auto out_rms = run_gpu_rms_noise_map(big_plane, rows, cols, box);

  REQUIRE(out_rms.size() == rows * cols);
  CHECK_THAT(out_rms, Catch::Matchers::Approx(expected).epsilon(1e-5));
}

TEST_CASE("gpu_rms_noise_map stays accurate on a large plane with a wide box", "[gpu][rms_noise_map]")
{
  constexpr size_t rows = 3072;
  constexpr size_t cols = 3072;
  constexpr long box = 400;

  const std::vector<float> big_plane = make_plane(rows * cols, 777ULL);
  const std::vector<float> expected = host_rms_integral_image(big_plane, rows, cols, box);
  const auto out_rms = run_gpu_rms_noise_map(big_plane, rows, cols, box);

  REQUIRE(out_rms.size() == rows * cols);
  CHECK_THAT(out_rms, Catch::Matchers::Approx(expected).epsilon(1e-5));
}
