// Runs gpu_rms_noise_map on the plane above with its scratch and output filled with `prefill`, like per-thread scratch
// holding an earlier band.
std::vector<float> run_gpu_rms_noise_map(const std::vector<float> &plane_values, size_t n_rows, size_t n_cols,
                                         long box, float prefill = 0.F)
{
  const size_t n_plane_pixels = n_rows * n_cols;

  const auto device_plane = upload(plane_values);
  auto device_rows = upload(std::vector<float>(n_plane_pixels, prefill));
  auto device_out = upload(std::vector<float>(n_plane_pixels, prefill));

  const Stream stream;
  gpu_rms_noise_map(device_plane, n_rows, n_cols, box, device_rows, device_out, stream);
  return download(device_out, stream);
}

std::vector<float> make_plane(size_t n_pixels, unsigned long long seed)
{
  std::mt19937_64 engine(seed);
  std::vector<float> values(n_pixels);
  for (auto &value : values)
  {
    const double unit = static_cast<double>(engine() >> 11) / 9007199254740992.;
    value = static_cast<float>((unit * 2. - 1.) * 3.);
  }
  return values;
}

// Independent host oracle: sum of plane^2 over the window [i-radius, i-radius+window) clamped to the plane, divided by
// the window's sample count, square rooted. Accumulated in double.
std::vector<float> host_rms_noise_map(const std::vector<float> &plane_values, size_t n_rows, size_t n_cols, long box)
{
  const long radius = box / 2;
  const long window = box > 0 ? box : 1;
  std::vector<float> out(n_rows * n_cols);

  for (size_t i_y = 0; i_y < n_rows; ++i_y)
  {
    const long y0 = std::max<long>(static_cast<long>(i_y) - radius, 0);
    const long y1 = std::min<long>(static_cast<long>(i_y) - radius + window, static_cast<long>(n_rows));
    for (size_t i_x = 0; i_x < n_cols; ++i_x)
    {
      const long x0 = std::max<long>(static_cast<long>(i_x) - radius, 0);
      const long x1 = std::min<long>(static_cast<long>(i_x) - radius + window, static_cast<long>(n_cols));

      double acc = 0.;
      for (long y = y0; y < y1; ++y)
      {
        for (long x = x0; x < x1; ++x)
        {
          const double value = plane_values[y * n_cols + x];
          acc += value * value;
        }
      }

      const double count = static_cast<double>((y1 - y0) * (x1 - x0));
      out[i_y * n_cols + i_x] = static_cast<float>(std::sqrt(acc / count));
    }
  }
  return out;
}

// Same quantity via a double integral image of plane^2, giving each clamped window sum in O(1). A different algorithm
// from the kernel's row/column sliding sums, so the two agree only if both are numerically sound.
std::vector<float> host_rms_integral_image(const std::vector<float> &plane_values, size_t n_rows, size_t n_cols, long box)
{
  const long radius = box / 2;
  const long window = box > 0 ? box : 1;
  const size_t stride = n_cols + 1;
  std::vector<double> integral((n_rows + 1) * stride, 0.);

  for (size_t i_y = 0; i_y < n_rows; ++i_y)
  {
    for (size_t i_x = 0; i_x < n_cols; ++i_x)
    {
      const double value = plane_values[i_y * n_cols + i_x];
      integral[(i_y + 1) * stride + (i_x + 1)] =
          value * value + integral[i_y * stride + (i_x + 1)] + integral[(i_y + 1) * stride + i_x] -
          integral[i_y * stride + i_x];
    }
  }

  std::vector<float> out(n_rows * n_cols);
  for (size_t i_y = 0; i_y < n_rows; ++i_y)
  {
    const size_t y0 = static_cast<size_t>(std::max<long>(static_cast<long>(i_y) - radius, 0));
    const size_t y1 = static_cast<size_t>(std::min<long>(static_cast<long>(i_y) - radius + window, static_cast<long>(n_rows)));
    for (size_t i_x = 0; i_x < n_cols; ++i_x)
    {
      const size_t x0 = static_cast<size_t>(std::max<long>(static_cast<long>(i_x) - radius, 0));
      const size_t x1 = static_cast<size_t>(std::min<long>(static_cast<long>(i_x) - radius + window, static_cast<long>(n_cols)));

      const double acc = integral[y1 * stride + x1] - integral[y0 * stride + x1] - integral[y1 * stride + x0] +
                         integral[y0 * stride + x0];
      const double count = static_cast<double>((y1 - y0) * (x1 - x0));
      out[i_y * n_cols + i_x] = static_cast<float>(std::sqrt(acc / count));
    }
  }
  return out;
}
