TEST_CASE("gpu_snr_and_filters overwrites the stale values of out_snr and the histograms", "[gpu][snr_and_filters]")
{
  // out_snr and the histograms are per-thread scratch holding the previous band: the result may not depend on them.
  const auto from_zero = run_gpu_snr_and_filters(plane, noise_map, snr_cutoff, flux_cutoff, default_params(), accept);
  const auto from_nan = run_gpu_snr_and_filters(plane, noise_map, snr_cutoff, flux_cutoff, default_params(), accept,
                                                std::numeric_limits<float>::quiet_NaN(), 7);
  const auto from_garbage = run_gpu_snr_and_filters(plane, noise_map, snr_cutoff, flux_cutoff, default_params(), accept,
                                                    1.0e30F, 123456789);

  for (const auto *other : {&from_nan, &from_garbage})
  {
    CHECK_THAT(other->snr, Equals(from_zero.snr));
    CHECK_THAT(other->mask, Equals(from_zero.mask));
    CHECK_THAT(other->histograms, RangeEquals(from_zero.histograms));
    CHECK(other->min_sigma == from_zero.min_sigma);
    CHECK(other->max_sigma == from_zero.max_sigma);
  }
}

