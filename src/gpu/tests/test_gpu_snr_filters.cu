SnrFilterParams default_params()
{
  SnrFilterParams params;
  params.median_noise = 1.F;
  params.inv_band_size = 0.5F;
  params.band_start = 1;
  params.band_stop = 3;
  params.max_sigma_bin = static_cast<long>(max_sigma_bin);
  params.histogram_detail = 2;
  params.reject_noise_threshold = 1.2F;
  params.threshold = 1.F;
  return params;
}

struct Outputs
{
  std::vector<float> snr;
  std::string mask; // one '0' or '1' per pixel
  std::array<std::vector<unsigned long long>, 3> histograms;
  float min_sigma;
  float max_sigma;
};

// Runs gpu_snr_and_filters on the data above. Empty cutoff vectors pass a null pointer. `out_snr` and the histograms
// start filled with the given values, like per-thread scratch holding an earlier band.
Outputs run_gpu_snr_and_filters(const std::vector<float> &plane_values, const std::vector<float> &noise_values,
                                const std::vector<float> &snr_cutoff_values, const std::vector<float> &flux_cutoff_values,
                                const SnrFilterParams &params, const std::string &accepted,
                                float snr_prefill = 0.F, unsigned long long histogram_prefill = 0)
{
  const size_t n = plane_values.size();
  const size_t n_bins = static_cast<size_t>(2 * params.max_sigma_bin);

  PinnedVector<float> host_plane(plane_values.begin(), plane_values.end());
  PinnedVector<float> host_noise(noise_values.begin(), noise_values.end());
  PinnedVector<float> host_snr_cutoff(snr_cutoff_values.begin(), snr_cutoff_values.end());
  PinnedVector<float> host_flux_cutoff(flux_cutoff_values.begin(), flux_cutoff_values.end());
  PinnedVector<float> host_out(n, snr_prefill);
  PinnedVector<float> host_median_noise(1, params.median_noise);
  PinnedVector<uint8_t> host_mask(n);
  for (size_t i_pixel = 0; i_pixel < n; ++i_pixel)
  {
    host_mask[i_pixel] = accepted[i_pixel] == '1';
  }
  PinnedVector<unsigned long long> host_histogram0(n_bins, histogram_prefill);
  PinnedVector<unsigned long long> host_histogram1(n_bins, histogram_prefill);
  PinnedVector<unsigned long long> host_histogram2(n_bins, histogram_prefill);
  PinnedVector<float> host_min(1);
  PinnedVector<float> host_max(1);

  DeviceVector<float> device_plane(n);
  DeviceVector<float> device_noise(n);
  DeviceVector<float> device_snr_cutoff(snr_cutoff_values.size());
  DeviceVector<float> device_flux_cutoff(flux_cutoff_values.size());
  DeviceVector<float> device_out(n);
  DeviceVector<float> device_median_noise(1);
  DeviceVector<uint8_t> device_mask(n);
  DeviceVector<unsigned long long> device_histogram0(n_bins);
  DeviceVector<unsigned long long> device_histogram1(n_bins);
  DeviceVector<unsigned long long> device_histogram2(n_bins);
  DeviceVector<float> device_min(1);
  DeviceVector<float> device_max(1);

  const bool snr_cutoff_enabled = !snr_cutoff_values.empty();
  const bool flux_cutoff_enabled = !flux_cutoff_values.empty();

  cudaStream_t stream{};
  gpuStreamCreate(&stream);

  gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_plane.data()), thrust::raw_pointer_cast(host_plane.data()),
                             n * sizeof(float), stream);
  gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_noise.data()), thrust::raw_pointer_cast(host_noise.data()),
                             n * sizeof(float), stream);
  gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_out.data()), thrust::raw_pointer_cast(host_out.data()),
                             n * sizeof(float), stream);
  gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_median_noise.data()),
                             thrust::raw_pointer_cast(host_median_noise.data()), sizeof(float), stream);
  gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_mask.data()), thrust::raw_pointer_cast(host_mask.data()), n,
                             stream);
  gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_histogram0.data()),
                             thrust::raw_pointer_cast(host_histogram0.data()), n_bins * sizeof(unsigned long long),
                             stream);
  gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_histogram1.data()),
                             thrust::raw_pointer_cast(host_histogram1.data()), n_bins * sizeof(unsigned long long),
                             stream);
  gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_histogram2.data()),
                             thrust::raw_pointer_cast(host_histogram2.data()), n_bins * sizeof(unsigned long long),
                             stream);
  if (snr_cutoff_enabled)
  {
    gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_snr_cutoff.data()),
                               thrust::raw_pointer_cast(host_snr_cutoff.data()),
                               snr_cutoff_values.size() * sizeof(float), stream);
  }
  if (flux_cutoff_enabled)
  {
    gpuMemcpyHostToDeviceAsync(thrust::raw_pointer_cast(device_flux_cutoff.data()),
                               thrust::raw_pointer_cast(host_flux_cutoff.data()),
                               flux_cutoff_values.size() * sizeof(float), stream);
  }

  gpu_snr_and_filters(
      thrust::raw_pointer_cast(device_plane.data()), thrust::raw_pointer_cast(device_noise.data()),
      snr_cutoff_enabled ? thrust::raw_pointer_cast(device_snr_cutoff.data()) : nullptr,
      flux_cutoff_enabled ? thrust::raw_pointer_cast(device_flux_cutoff.data()) : nullptr,
      thrust::raw_pointer_cast(device_median_noise.data()), n, params,
      thrust::raw_pointer_cast(device_out.data()), reinterpret_cast<bool *>(thrust::raw_pointer_cast(device_mask.data())),
      thrust::raw_pointer_cast(device_histogram0.data()), thrust::raw_pointer_cast(device_histogram1.data()),
      thrust::raw_pointer_cast(device_histogram2.data()), thrust::raw_pointer_cast(device_min.data()),
      thrust::raw_pointer_cast(device_max.data()), stream);

  gpuMemcpyDeviceToHostAsync(thrust::raw_pointer_cast(host_out.data()), thrust::raw_pointer_cast(device_out.data()),
                             n * sizeof(float), stream);
  gpuMemcpyDeviceToHostAsync(thrust::raw_pointer_cast(host_mask.data()), thrust::raw_pointer_cast(device_mask.data()), n,
                             stream);
  gpuMemcpyDeviceToHostAsync(thrust::raw_pointer_cast(host_histogram0.data()),
                             thrust::raw_pointer_cast(device_histogram0.data()), n_bins * sizeof(unsigned long long),
                             stream);
  gpuMemcpyDeviceToHostAsync(thrust::raw_pointer_cast(host_histogram1.data()),
                             thrust::raw_pointer_cast(device_histogram1.data()), n_bins * sizeof(unsigned long long),
                             stream);
  gpuMemcpyDeviceToHostAsync(thrust::raw_pointer_cast(host_histogram2.data()),
                             thrust::raw_pointer_cast(device_histogram2.data()), n_bins * sizeof(unsigned long long),
                             stream);
  gpuMemcpyDeviceToHostAsync(thrust::raw_pointer_cast(host_min.data()), thrust::raw_pointer_cast(device_min.data()),
                             sizeof(float), stream);
  gpuMemcpyDeviceToHostAsync(thrust::raw_pointer_cast(host_max.data()), thrust::raw_pointer_cast(device_max.data()),
                             sizeof(float), stream);

  gpuStreamSynchronize(stream);
  gpuStreamDestroy(stream);

  std::string mask;
  mask.reserve(n);
  for (size_t i_pixel = 0; i_pixel < n; ++i_pixel)
  {
    mask += host_mask[i_pixel] ? '1' : '0';
  }
  return {std::vector<float>(host_out.begin(), host_out.end()), mask,
          {std::vector<unsigned long long>(host_histogram0.begin(), host_histogram0.end()),
           std::vector<unsigned long long>(host_histogram1.begin(), host_histogram1.end()),
           std::vector<unsigned long long>(host_histogram2.begin(), host_histogram2.end())},
          host_min[0], host_max[0]};
}

// A deterministic ramp for the coverage cases, where a hand-written expected array would be unwieldy.
std::vector<float> make_pattern(size_t n, float scale, int stride, int modulus)
{
  std::vector<float> values(n);
  for (size_t i_pixel = 0; i_pixel < n; ++i_pixel)
  {
    values[i_pixel] = scale * static_cast<float>(static_cast<int>((i_pixel * stride) % modulus));
  }
  return values;
}

// Reference computed on the host with the documented formula, independent of the kernel. Every operation is a single
// IEEE float32 op in the same order as the kernel, so the comparison is exact.
Outputs host_snr_and_filters(const std::vector<float> &plane_values, const std::vector<float> &noise_values,
                             const std::vector<float> &snr_cutoff_values, const std::vector<float> &flux_cutoff_values,
                             const SnrFilterParams &params, const std::string &accepted)
{
  const size_t n = plane_values.size();
  const size_t n_bins = static_cast<size_t>(2 * params.max_sigma_bin);
  const bool snr_cutoff_enabled = !snr_cutoff_values.empty();
  const bool flux_cutoff_enabled = !flux_cutoff_values.empty();

  Outputs out;
  out.snr.resize(n);
  out.histograms[0].assign(n_bins, 0);
  out.histograms[1].assign(n_bins, 0);
  out.histograms[2].assign(n_bins, 0);
  out.min_sigma = std::numeric_limits<float>::infinity();
  out.max_sigma = std::numeric_limits<float>::lowest();

  for (size_t i_pixel = 0; i_pixel < n; ++i_pixel)
  {
    const float noise = noise_values[i_pixel];
    const bool valid = noise != 0.F && std::isfinite(noise);
    const float plane_val = plane_values[i_pixel];
    const float snr = valid ? plane_val / noise : 0.F;

    bool mask = accepted[i_pixel] == '1';
    mask &= valid;
    const bool mask0 = mask;

    float snr_cutoff_threshold = 0.F;
    if (snr_cutoff_enabled)
    {
      for (long i_channel = params.band_start; i_channel < params.band_stop; ++i_channel)
      {
        snr_cutoff_threshold += snr_cutoff_values[i_channel * n + i_pixel];
      }
      snr_cutoff_threshold *= params.inv_band_size;
    }
    float flux_cutoff_threshold = 0.F;
    if (flux_cutoff_enabled)
    {
      for (long i_channel = params.band_start; i_channel < params.band_stop; ++i_channel)
      {
        flux_cutoff_threshold += flux_cutoff_values[i_channel * n + i_pixel];
      }
      flux_cutoff_threshold *= params.inv_band_size;
    }

    const bool mask1 = mask0 && (!snr_cutoff_enabled || std::abs(snr) >= snr_cutoff_threshold);
    const bool mask2 = mask1 && (!flux_cutoff_enabled || std::abs(plane_val) >= flux_cutoff_threshold);
    const bool mask3 = mask2 && (params.reject_noise_threshold == 0.F ||
                                 noise <= params.median_noise * params.reject_noise_threshold);

    float bin_index = std::floor(snr + params.max_sigma_bin);
    if (bin_index == 2 * params.max_sigma_bin)
    {
      bin_index -= 1.F;
    }
    if (0.F <= bin_index && bin_index < 2 * params.max_sigma_bin)
    {
      const auto bin = static_cast<size_t>(bin_index);
      if (mask0 && params.histogram_detail > 1)
      {
        out.histograms[0][bin]++;
      }
      if (mask1 && params.histogram_detail > 1)
      {
        out.histograms[1][bin]++;
      }
      if (mask2 && params.histogram_detail > 0)
      {
        out.histograms[2][bin]++;
      }
    }

    if (mask3)
    {
      out.min_sigma = std::min(out.min_sigma, snr);
      out.max_sigma = std::max(out.max_sigma, snr);
    }

    out.snr[i_pixel] = snr;
    out.mask += (mask3 && std::abs(snr) >= params.threshold) ? '1' : '0';
  }
  return out;
}

void check_snr_and_filters_matches_host(size_t n)
{
  const std::vector<float> plane_values = make_pattern(n, 0.5F, 7, 50);
  std::vector<float> noise_values(n);
  for (size_t i_pixel = 0; i_pixel < n; ++i_pixel)
  {
    noise_values[i_pixel] = 0.25F + 0.01F * static_cast<float>(static_cast<int>((i_pixel * 13) % 80));
  }
  std::vector<float> snr_cutoff_values(2 * n);
  std::vector<float> flux_cutoff_values(2 * n);
  for (size_t i_channel = 0; i_channel < 2; ++i_channel)
  {
    for (size_t i_pixel = 0; i_pixel < n; ++i_pixel)
    {
      snr_cutoff_values[i_channel * n + i_pixel] =
          0.1F * static_cast<float>(static_cast<int>(((i_pixel + i_channel * 5) * 11) % 30));
      flux_cutoff_values[i_channel * n + i_pixel] =
          0.1F * static_cast<float>(static_cast<int>(((i_pixel + i_channel * 7) * 3) % 30));
    }
  }
  const std::string accepted(n, '1');

  SnrFilterParams params = default_params();
  params.band_start = 0;
  params.band_stop = 2;
  params.inv_band_size = 0.5F;

  const auto expected = host_snr_and_filters(plane_values, noise_values, snr_cutoff_values, flux_cutoff_values, params,
                                             accepted);
  const auto out = run_gpu_snr_and_filters(plane_values, noise_values, snr_cutoff_values, flux_cutoff_values, params,
                                           accepted);

  REQUIRE(out.snr.size() == n);
  CHECK_THAT(out.snr, Equals(expected.snr));
  CHECK_THAT(out.mask, Equals(expected.mask));
  CHECK_THAT(out.histograms, RangeEquals(expected.histograms));
  CHECK(out.min_sigma == expected.min_sigma);
  CHECK(out.max_sigma == expected.max_sigma);
}
